export const LanguageProvider = ({ children }) => {
  const [lang, setLang] = useState(() => {
    try {
      return localStorage.getItem('farmora_lang') || 'en';
    } catch {
      return 'en';
    }
  });

  useEffect(() => {
    try {
      localStorage.setItem('farmora_lang', lang);
      document.documentElement.lang = lang;
    } catch {}
  }, [lang]);

  const t = (key, fallback = '') => {
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
    return dict[key] || TRANSLATIONS.en[key] || fallback || key;
  };

  const getCropName = (crop) => {
    if (!crop) return '';
    if (lang === 'mr' && crop.localNames?.mr) {
      return `${crop.localNames.mr} (${crop.name})`;
    }
    if (lang === 'hi' && crop.localNames?.hi) {
      return `${crop.localNames.hi} (${crop.name})`;
    }
    return crop.name;
  };

  const getCategoryName = (category) => {
    if (!category) return '';
    const name = typeof category === 'string' ? category : category.name;
    if (typeof category === 'object' && category?.localNames?.[lang]) {
      return category.localNames[lang];
    }
    const mapping = {
      mr: {
        'Pest infestation': 'कीड प्रादुर्भाव',
        'Crop diseases': 'पीक रोग',
        'Nutrient deficiency': 'अन्नद्रव्य कमतरता',
        'Irrigation problems': 'पाणी व सिंचन समस्या',
        'Weather damage': 'हवामान नुकसान',
        'Weed management': 'तण व्यवस्थापन',
        'Crop Disease': 'पीक रोग',
        'Pest Attack': 'कीड प्रादुर्भाव',
        'Irrigation Problem': 'पाणी व सिंचन समस्या',
        'Fertilizer Issue': 'अन्नद्रव्य कमतरता',
        'Weather/Crop Damage': 'हवामान नुकसान',
      },
      hi: {
        'Pest infestation': 'कीट प्रकोप',
        'Crop diseases': 'फसल रोग',
        'Nutrient deficiency': 'पोषक तत्वों की कमी',
        'Irrigation problems': 'सिंचाई की समस्याएं',
        'Weather damage': 'मौसम से नुकसान',
        'Weed management': 'खरपतवार प्रबंधन',
        'Crop Disease': 'फसल रोग',
        'Pest Attack': 'कीट प्रकोप',
        'Irrigation Problem': 'सिंचाई की समस्याएं',
        'Fertilizer Issue': 'पोषक तत्वों की कमी',
        'Weather/Crop Damage': 'मौसम से नुकसान',
      },
    };
    return mapping[lang]?.[name] || name;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, getCropName, getCategoryName }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    return {
      lang: 'en',
      setLang: () => {},
      t: (key, fallback) => fallback || key,
      getCropName: (crop) => crop?.name || '',
      getCategoryName: (category) => (typeof category === 'string' ? category : category?.name || ''),
    };
  }
  return context;
};

export default LanguageContext;
